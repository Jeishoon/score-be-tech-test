package postcode

import (
	"sort"
)

// Builder collects NSPL rows and produces a Table. Each sector and district
// is assigned the region that most of its postcodes fall in.
//
// Live postcodes decide the result. Terminated postcodes only count for a
// sector or district that has no live postcodes at all, so that old addresses
// on existing cases still resolve.
type Builder struct {
	live, terminated tally
	Skipped          int // rows with an invalid postcode or unmapped region
}

func NewBuilder() *Builder {
	return &Builder{live: tally{}, terminated: tally{}}
}

// Add records one NSPL row: the postcode (any spacing), its region code
// (e.g. "E12000004") and whether it has been terminated.
func (b *Builder) Add(rawPostcode, regionCode string, terminated bool) {
	region, ok := RegionCodes[regionCode]
	if !ok {
		b.Skipped++
		return
	}
	pc, err := Parse(rawPostcode)
	if err != nil {
		b.Skipped++
		return
	}
	t := b.live
	if terminated {
		t = b.terminated
	}
	t.add("s:"+pc.Sector(), region)
	t.add("d:"+pc.District(), region)
}

// Stats about a built table, for logging.
type Stats struct {
	Sectors, Districts int
	MixedSectors       int // sectors whose postcodes span more than one region
}

// Table returns the built lookup table.
func (b *Builder) Table(source string) (*Table, Stats) {
	t := &Table{
		Source:    source,
		Note:      "Postcode sector/district to ONS region, majority vote over NSPL postcodes. Generated by cmd/postcodeconvert; do not edit by hand.",
		Sectors:   map[string]string{},
		Districts: map[string]string{},
	}
	var st Stats
	keys := map[string]bool{}
	for k := range b.live {
		keys[k] = true
	}
	for k := range b.terminated {
		keys[k] = true
	}
	for k := range keys {
		votes := b.live[k]
		if len(votes) == 0 {
			votes = b.terminated[k]
		}
		region := majority(votes)
		switch k[:2] {
		case "s:":
			t.Sectors[k[2:]] = region
			if len(votes) > 1 {
				st.MixedSectors++
			}
		case "d:":
			t.Districts[k[2:]] = region
		}
	}
	st.Sectors, st.Districts = len(t.Sectors), len(t.Districts)
	return t, st
}

// tally counts region votes per key, e.g. tally["NG1 2"]["East Midlands"] = 512.
type tally map[string]map[string]int

func (t tally) add(key, region string) {
	if t[key] == nil {
		t[key] = map[string]int{}
	}
	t[key][region]++
}

// majority returns the region with the most votes; ties go to the
// alphabetically first region so the output is stable between runs.
func majority(votes map[string]int) string {
	regions := make([]string, 0, len(votes))
	for r := range votes {
		regions = append(regions, r)
	}
	sort.Strings(regions)
	best := ""
	for _, r := range regions {
		if best == "" || votes[r] > votes[best] {
			best = r
		}
	}
	return best
}
